    private val decks = HashMap<List<String>, ArrayList<String>>()
    private val rnd = java.util.Random()

    /** The next line of [list] (and of [extra], lines written today), dealt like cards. */
    fun deal(list: List<String>, extra: List<String> = emptyList()): String {
        val all = if (extra.isEmpty()) list else list + extra
        val deck = decks.getOrPut(list) { ArrayList() }
        if (deck.isEmpty()) { deck.addAll(all); deck.shuffle(rnd) }
        return deck.removeAt(deck.size - 1)
    }
