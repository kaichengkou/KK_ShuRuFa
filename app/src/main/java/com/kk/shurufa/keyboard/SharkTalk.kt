    private val decks = HashMap<List<*>, ArrayList<Any>>()
    private val rnd = java.util.Random()

    /** The next of [list] (and of [extra]), dealt like cards. */
    @Suppress("UNCHECKED_CAST")
    fun <T : Any> deal(list: List<T>, extra: List<T> = emptyList()): T {
        val deck = decks.getOrPut(list) { ArrayList() }
        if (deck.isEmpty()) { deck.addAll(list + extra); deck.shuffle(rnd) }
        return deck.removeAt(deck.size - 1) as T
    }
